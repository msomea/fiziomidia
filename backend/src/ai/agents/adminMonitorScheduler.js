import cron from "node-cron";
import AIConfiguration from "../../models/AIConfiguration.js";
import AIActivityLog from "../../models/AIActivityLog.js";
import { generateReport } from "./virtualAdminAgent.js";
import { resolveAdminEmails } from "../services/approvalService.js";
import { sendEmail, EMAIL_FROM } from "../../services/sendEmailService.js";
import config from "../../config/index.js";

/*
Virtual Administrator Scheduler — Phase 3.
Reads the virtualAdmin agent's cron `schedule` from AIConfiguration
(null → manual trigger only via POST /api/ai/admin/report).
Each run generates the daily monitoring report and emails the
predefined admin review addresses. READ-ONLY — never mutates data.
*/

const escapeHtml = (s) =>
  String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

export const runAdminReportJob = async () => {
  const cfg = await AIConfiguration.findOne().lean();
  if (cfg && cfg.enabled === false) return { ok: false, reason: "AI disabled" };

  const result = await generateReport();
  if (!result.ok) {
    return { ok: false, reason: result.error, code: result.code };
  }

  // Stamp lastRunAt
  await AIConfiguration.updateOne(
    {},
    { $set: { "agents.$[a].lastRunAt": new Date() } },
    { arrayFilters: [{ "a.name": "virtualAdmin" }] },
  );

  // Email the report to admin review addresses
  try {
    const to = await resolveAdminEmails();
    if (to.length > 0) {
      const base = config.clientUrl || "https://fiziomidia.org";
      const anomalyHtml = result.anomalies?.length
        ? `<p style="color:#b45309"><strong>Anomalies flagged:</strong><br>${result.anomalies.map((a) => `• ${escapeHtml(a)}`).join("<br>")}</p>`
        : "";
      await sendEmail({
        to,
        from: EMAIL_FROM.ADMIN,
        subject: "[FizioMidia AI] Daily admin report",
        html: `
          <div style="font-family:Arial,sans-serif;max-width:640px">
            <h2 style="color:#0d6e6e">Daily Platform Report</h2>
            ${anomalyHtml}
            <div style="background:#f4f8f8;border:1px solid #d7eaea;border-radius:8px;padding:16px;white-space:pre-wrap;font-size:14px;line-height:1.6">${escapeHtml(result.report)}</div>
            <p style="margin-top:16px"><a href="${base}/admin" style="background:#0d6e6e;color:#fff;padding:10px 18px;border-radius:6px;text-decoration:none">Open Admin Dashboard</a></p>
            <p style="color:#888;font-size:12px">Generated by the Virtual Administrator agent. All figures are exact database counts.</p>
          </div>`,
      });
    }
  } catch (err) {
    console.error("Admin report email failed:", err.message);
  }

  await AIActivityLog.create({
    agent: "virtualAdmin",
    action: "SCHEDULED_RUN",
    details: { anomalies: result.anomalies?.length || 0 },
  });

  return { ok: true, anomalies: result.anomalies?.length || 0 };
};

let scheduled = false;

/**
 * Register the cron job if a schedule is configured.
 * Called once at server startup (app.js). Restart required after
 * config change (documented limitation, same as forum scheduler).
 */
export const registerAdminScheduler = async () => {
  if (scheduled) return;
  const cfg = await AIConfiguration.findOne().lean();
  const agentCfg = cfg?.agents?.find((a) => a.name === "virtualAdmin");
  const expr = agentCfg?.schedule;

  if (!expr || agentCfg?.enabled === false) {
    console.log("🗓️  Admin report scheduler: no schedule configured — manual triggers only");
    return;
  }
  if (!cron.validate(expr)) {
    console.warn(`🗓️  Admin report scheduler: invalid cron expression "${expr}" — disabled`);
    return;
  }

  cron.schedule(expr, async () => {
    try {
      const result = await runAdminReportJob();
      console.log("🗓️  Admin report job:", result);
    } catch (err) {
      console.error("🗓️  Admin report job failed:", err);
    }
  });
  scheduled = true;
  console.log(`🗓️  Admin report scheduler registered: "${expr}"`);
};
